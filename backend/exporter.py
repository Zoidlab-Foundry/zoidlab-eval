"""Standardized Nyquest package export for Eval — a portable evaluation report."""
import datetime


def to_package(run, results):
    return {
        "schema_version": "1.0",
        "package_type": "nyquest_eval_report",
        "generated_at": datetime.datetime.utcnow().isoformat() + "Z",
        "source_app": "eval",
        "run": {"id": run["id"], "target": run["target_name"], "model": run.get("target_model"),
                "testset": run["testset_name"], "criteria": [c["name"] for c in run.get("criteria", [])],
                "config": run["config"], "status": run["status"], "billing_mode": run.get("billing_mode"),
                "created_at": run["created_at"]},
        "summary": run.get("summary", {}),
        "results": [{
            "case_id": r["case_id"], "input": r["input"], "ok": r["ok"], "passed": r["passed"],
            "overall": r["overall"], "scores": r["scores"], "latency_ms": r["latency_ms"],
            "cost_usd": r["cost_usd"], "error": r.get("error"),
        } for r in results],
        "disclaimer": "Answers are generated by the target model and scored by a judge model on the "
                      "Nyquest relay at run time. Scores are a judge model's opinion (1-5), not ground "
                      "truth; the production-readiness verdict is threshold-based over those scores.",
    }


def to_yaml(pkg):
    def emit(v, ind=0):
        pad = "  " * ind
        if isinstance(v, dict):
            out = []
            for k, val in v.items():
                if isinstance(val, (dict, list)) and val:
                    out.append(f"{pad}{k}:"); out.append(emit(val, ind + 1))
                else:
                    out.append(f"{pad}{k}: {_scalar(val)}")
            return "\n".join(out)
        if isinstance(v, list):
            out = []
            for item in v:
                if isinstance(item, (dict, list)):
                    out.append(f"{pad}-"); out.append(emit(item, ind + 1))
                else:
                    out.append(f"{pad}- {_scalar(item)}")
            return "\n".join(out)
        return f"{pad}{_scalar(v)}"

    def _scalar(v):
        if v is None:
            return "null"
        if isinstance(v, bool):
            return "true" if v else "false"
        s = str(v)
        return f'"{s}"' if (":" in s or "#" in s) else s

    return emit(pkg) + "\n"
